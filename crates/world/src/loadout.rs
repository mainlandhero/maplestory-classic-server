/// Everything one first-job branch needs in hand, and every skill it has.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Loadout {
    /// `100`, `200`, `300` or `400` - `crate::jobs::FIRST_JOBS` order.
    pub job: u16,
    /// The name this client's own `QuestData/10001.img` gives the job, matching
    /// `crate::jobs::FirstJob::job_name`.
    pub job_name: &'static str,
    /// What to hand over, in the order to hand it over. **Empty is a measurement**, not an
    /// omission - see [`MAGICIAN`].
    pub pieces: &'static [Piece],
    /// A second way to satisfy the same gates, when the archive offers one. The Bowman
    /// skills all carry `weapon2 = 46`, so a crossbow works everywhere a bow does.
    pub alternative: &'static [Piece],
    /// Every skill of this branch, with its measured gate. All six, always - a table that
    /// listed only the gated ones would not show that the other four are ungated.
    pub skills: &'static [SkillGate],
    /// The one thing about this branch that could still cost a run, or `None`.
    pub caveat: Option<&'static str>,
}

impl Loadout {
    /// The skills no item gates - castable the moment they are learned.
    pub fn ungated_skills(&self) -> impl Iterator<Item = &SkillGate> {
        self.skills.iter().filter(|s| s.weapon_codes.is_empty())
    }

    /// The skills that will not cast without a weapon of the right class.
    pub fn gated_skills(&self) -> impl Iterator<Item = &SkillGate> {
        self.skills.iter().filter(|s| !s.weapon_codes.is_empty())
    }

    /// Whether this branch needs no item at all to cast every one of its skills.
    pub fn needs_nothing(&self) -> bool {
        self.pieces.is_empty()
    }

    /// The `!item` lines that hand the whole kit over.
    pub fn gm_lines(&self) -> Vec<String> {
        self.pieces.iter().map(Piece::gm_line).collect()
    }

    /// Every piece this character could not equip, with the failing clauses.
    pub fn unequippable(&self, chr: &Character) -> Vec<(&Piece, Vec<String>)> {
        self.pieces
            .iter()
            .filter_map(|p| {
                let unmet = p.req.unmet_clauses(chr);
                if unmet.is_empty() { None } else { Some((p, unmet)) }
            })
            .collect()
    }
}

