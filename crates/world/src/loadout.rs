/// One skill's item gate, transcribed from `gm-handbook/skills.txt`. **[L]**
///
/// A test cross-checks every field of every row here against that file when it is present.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct SkillGate {
    pub skill_id: u32,
    pub name: &'static str,
    /// The `weapon`, `weapon2`, `weapon3`, `weapon4` columns, in that order, with the empty
    /// ones dropped. **Empty means the skill has no weapon column at all**, which is
    /// nineteen of the twenty-four first-job skills.
    pub weapon_codes: &'static [u32],
    /// `bulletConsume`. `None` is an **absent column**, not zero - and the difference is the
    /// whole reason Lucky Seven is a separate case from Arrow Blow.
    pub bullet_consume: Option<u32>,
    /// `bulletCount`, i.e. **projectiles per cast**. `research/magician-first-job.md` reads
    /// it off Energy Bolt's `common` node. **[L]** This is *not* an ammunition requirement -
    /// Energy Bolt is a wand spell and carries `1`.
    pub bullet_count: Option<u32>,
}

impl SkillGate {
    /// Whether a weapon class satisfies this skill's `weapon` columns. A skill with no
    /// weapon column is castable with anything, including bare hands.
    pub fn castable_with(&self, class: Option<WeaponClass>) -> bool {
        if self.weapon_codes.is_empty() {
            return true;
        }
        class.is_some_and(|c| self.weapon_codes.contains(&c.code()))
    }
}

