/// The four branches, in `crate::jobs::FIRST_JOBS` order.
pub const LOADOUTS: [Loadout; 4] = [WARRIOR, MAGICIAN, BOWMAN, THIEF];

/// The kit for a first job. `None` for anything that is not `100`, `200`, `300` or `400`.
///
/// **Exact, not by branch.** A second-job id resolves to nothing rather than silently
/// answering with the first job's kit, because a second-job character's skills are not in
/// this table and pretending otherwise would be the kind of plausible-looking wrong answer
/// `CLAUDE.md` is about.
pub fn loadout_for(job: u16) -> Option<&'static Loadout> {
    LOADOUTS.iter().find(|l| l.job == job)
}

/// Every gate in the table, across all four branches.
pub fn all_skill_gates() -> impl Iterator<Item = &'static SkillGate> {
    LOADOUTS.iter().flat_map(|l| l.skills.iter())
}

/// The gate for one skill id.
pub fn gate_for_skill(skill_id: u32) -> Option<&'static SkillGate> {
    all_skill_gates().find(|s| s.skill_id == skill_id)
}

/// A weapon class in plain English, for a line a person reads.
///
/// The **names** are `research/damage-formula.md` §1.4's column, which is `[D]`: they were
/// derived by matching the 1H-axe arm (`2 -> 2.4`, `3 -> 1.2`) and the bow arm (`4 -> 2.5`)
/// against the meowdb table, which agrees for all eight families. The **codes** are `[L]`.
///
/// This is the one thing this module adds to [`WeaponClass`]; the mapping from code to class
/// is that enum's job and is not repeated here.
pub fn weapon_name(class: WeaponClass) -> &'static str {
    match class {
        WeaponClass::OneHandSword => "one-handed sword",
        WeaponClass::OneHandAxe => "one-handed axe",
        WeaponClass::OneHandBlunt => "one-handed blunt weapon",
        WeaponClass::Dagger => "dagger",
        WeaponClass::Wand => "wand",
        WeaponClass::Staff => "staff",
        WeaponClass::BareHands => "bare hands",
        WeaponClass::TwoHandSword => "two-handed sword",
        WeaponClass::TwoHandAxe => "two-handed axe",
        WeaponClass::TwoHandBlunt => "two-handed blunt weapon",
        WeaponClass::Spear => "spear",
        WeaponClass::Polearm => "polearm",
        WeaponClass::Bow => "bow",
        WeaponClass::Crossbow => "crossbow",
        WeaponClass::Claw => "claw",
    }
}

/// The plain-English name for a raw `Skill.wz` `weapon` code, or `None` when the code has no
/// arm in the client's weapon switch (`34`, `35`, `36`) or is outside `30..=47` entirely.
pub fn weapon_name_for_code(code: u32) -> Option<&'static str> {
    WeaponClass::from_code(code).map(weapon_name)
}

