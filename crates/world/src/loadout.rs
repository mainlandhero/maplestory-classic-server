    // -- cross-checks against the generated files ----------------------------------------
    //
    // `gm-handbook/` is generated and gitignored, so these skip when it is absent - the same
    // convention `net::quest`'s requirement-table test uses. Each one proves its parse can
    // find a positive control before asserting anything, because a silent negative here
    // would be a property of the parse rather than evidence.

    fn handbook(name: &str) -> Option<String> {
        std::fs::read_to_string(std::path::Path::new("../../gm-handbook").join(name)).ok()
    }

    /// One skill's gate columns as the generated file spells them.
    type SkillRow = (String, Vec<u32>, Option<u32>, Option<u32>);

    /// Parse `skills.txt` into `skillId -> {every distinct (name, weapon..weapon4,
    /// bulletConsume, bulletCount) across that skill's levels}`, reading the column positions
    /// off the header rather than hard-coding them.
    ///
    /// **A set, not a single row, and that is a correction this test made itself.** The first
    /// version asserted these columns were level-invariant for every skill in the file and
    /// **it failed**: `3111002` Arrow Rain is `bulletConsume 7, bulletCount 7` at some levels
    /// and `8, 8` at others. That is a second-job skill, so it does not touch this table - but
    /// it means "these columns do not vary with level" is **false file-wide** and is only true
    /// for the 24 first-job skills. [`every_skill_gate_matches_the_generated_skill_archive`]
    /// asserts the invariance where this module actually relies on it and nowhere else.
    #[allow(clippy::type_complexity)]
    fn parse_skills(text: &str) -> std::collections::HashMap<u32, Vec<SkillRow>> {
        let header: Vec<&str> = text
            .lines()
            .find(|l| l.starts_with('#') && l.contains("skillId"))
            .expect("skills.txt has no header line")
            .trim_start_matches('#')
            .split(',')
            .map(str::trim)
            .collect();
        let col = |n: &str| header.iter().position(|h| *h == n).unwrap_or_else(|| panic!("no column {n}"));
        let (c_id, c_name) = (col("skillId"), col("name"));
        let (c_w, c_w2, c_w3, c_w4) = (col("weapon"), col("weapon2"), col("weapon3"), col("weapon4"));
        let (c_bc, c_bn) = (col("bulletConsume"), col("bulletCount"));

        let mut out = std::collections::HashMap::new();
        for line in text.lines().filter(|l| !l.starts_with('#') && !l.trim().is_empty()) {
            let f: Vec<&str> = line.split(',').map(str::trim).collect();
            assert_eq!(f.len(), header.len(), "row width differs from the header: {line}");
            let Ok(id) = f[c_id].parse::<u32>() else { continue };
            let weapons: Vec<u32> =
                [c_w, c_w2, c_w3, c_w4].iter().filter_map(|&c| f[c].parse::<u32>().ok()).collect();
            let row = (
                f[c_name].to_string(),
                weapons,
                f[c_bc].parse::<u32>().ok(),
                f[c_bn].parse::<u32>().ok(),
            );
            let seen: &mut Vec<SkillRow> = out.entry(id).or_default();
            if !seen.contains(&row) {
                seen.push(row);
            }
        }
        out
    }

    /// **The check this whole module rests on.** Every gate above, against the generated
    /// file, column by column.
    #[test]
    fn every_skill_gate_matches_the_generated_skill_archive() {
        let Some(text) = handbook("skills.txt") else { return };
        let table = parse_skills(&text);

        // Positive controls first: a parse that found nothing would pass every assertion
        // below by vacuity, and a wrong column index would too.
        // 176 distinct skills over 4164 rows - counted, not guessed. The first version of
        // this line asserted "> 300" from memory and failed against the real file, which is
        // the same class of mistake as every other unverified constant in this repo.
        assert!(
            table.len() >= 150,
            "skills.txt parsed to {} skills; this client has 176",
            table.len()
        );
        let three_snails = table.get(&1000).expect("skill 1000 Three Snails");
        assert_eq!(three_snails[0].0, "Three Snails");
        let bow_mastery = table.get(&3_100_000).expect("skill 3100000 Bow Mastery");
        assert_eq!(bow_mastery[0].1, vec![45], "Bow Mastery is the weapon-column control");
        // The instrument has to be able to SEE variation, or "one distinct row" below would
        // be a property of the parse. Arrow Rain is the control that it can.
        // 3111002 Arrow Rain runs bulletConsume/bulletCount 4,4 -> 5,5 -> 6,6 -> 7,7 -> 8,8
        // over its levels: five distinct rows, counted off the file.
        assert_eq!(
            table.get(&3_111_002).map(Vec::len),
            Some(5),
            "3111002 Arrow Rain varies its bullet columns with level; if this parse cannot \
             see that, it cannot see drift in the rows this module depends on either"
        );

        for l in LOADOUTS.iter() {
            for g in l.skills {
                let rows = table
                    .get(&g.skill_id)
                    .unwrap_or_else(|| panic!("{} ({}) is not in skills.txt", g.name, g.skill_id));
                assert_eq!(
                    rows.len(),
                    1,
                    "{} ({}) varies these columns with level, so a single SkillGate cannot \
                     describe it: {:?}",
                    g.name,
                    g.skill_id,
                    rows
                );
                let (name, weapons, bc, bn) = &rows[0];
                assert_eq!(name, g.name, "skill {}", g.skill_id);
                assert_eq!(weapons, &g.weapon_codes.to_vec(), "{} weapon columns", g.name);
                assert_eq!(*bc, g.bullet_consume, "{} bulletConsume", g.name);
                assert_eq!(*bn, g.bullet_count, "{} bulletCount", g.name);
            }
        }
    }

