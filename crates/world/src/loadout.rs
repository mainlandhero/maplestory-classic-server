/// Whether a piece is worn or fired.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum PieceKind {
    /// Goes in the Equip tab and then into the weapon slot.
    Weapon(WeaponClass),
    /// Goes in the USE tab and is picked up by the client - see [`AMMUNITION_TAB`].
    Ammunition,
}

/// One item to hand over, with the evidence for its id in one place.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Piece {
    pub item_id: u32,
    /// The name **verbatim from `gm-handbook/items.txt`**, which is generated from this
    /// client's own `String.wz`. A test pins it against that file.
    pub name: &'static str,
    pub kind: PieceKind,
    /// How many to give. `1` for a weapon; for ammunition this is the item's own
    /// `info/slotMax` from `gm-handbook/itemdata.txt`, so the stack lands in **one** slot.
    pub quantity: u16,
    pub req: Requirements,
    /// The skills whose **`Skill.wz` `weapon` or `bulletConsume` column this piece
    /// satisfies**. Measured, and deliberately narrow: a piece that merely makes a skill
    /// *useful* is not listed here, only one the archive actually gates on.
    pub unlocks: &'static [u32],
    /// Why this item and not another, in one line a person reads.
    pub why: &'static str,
}

impl Piece {
    /// The weapon class, if this is a weapon.
    pub fn weapon_class(&self) -> Option<WeaponClass> {
        match self.kind {
            PieceKind::Weapon(c) => Some(c),
            PieceKind::Ammunition => None,
        }
    }

    /// The bag this piece belongs in, by the same arithmetic the client's own
    /// `GetInventoryType` uses - see the module docs.
    pub fn inventory_tab(&self) -> Option<InventoryType> {
        InventoryType::for_item(self.item_id)
    }

    /// The `!item` line that hands this piece over.
    pub fn gm_line(&self) -> String {
        format!("!item {} {}", self.item_id, self.quantity)
    }
}

/// The bag ammunition has to be in. **[L]** - `FUN_1403e8af0` returns `itemId / 1_000_000`
/// for every non-equip id, and `2` is Consume/USE. See the module docs for the listing.
pub const AMMUNITION_TAB: InventoryType = InventoryType::Use;

