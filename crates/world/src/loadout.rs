//! What a character has to be **holding** before each first-job skill will cast.
//!
//! The owner wants to test all 24 first-job skills across the four branches in one session. Half
//! of them are gated on a weapon and two on ammunition, and a client run costs a manual
//! launch - so the concrete item ids belong in the repo before they start, not in the middle
//! of the run.
//!
//! Nothing here is wired. See the `WIRE IT LIKE THIS` note at the bottom of this file for
//! the `!kit` GM command this table exists to feed.
//!
//! # Where every number in this file came from
//!
//! * **`[L]`** - read off this client. `gm-handbook/skills.txt` (generated by
//!   `tools/dump_skills.py` from `Data/Skill/Skill_000.wz`), `gm-handbook/items.txt`,
//!   `gm-handbook/itemdata.txt`, and - for the requirement fields, which the generated files
//!   do **not** carry - the `info` node of each weapon image read directly out of
//!   `client-patched/Data/Character/Weapon/Weapon_000.wz` with `target/release/wz-dump.exe`.
//! * **`[D]`** - derived from two or more of those.
//! * **`[I]`** - inferred. There is very little of it here and every instance says so.
//!
//! # The gates, measured. `weapon` is absent far more often than expected
//!
//! All 24 first-job skills were enumerated out of `gm-handbook/skills.txt` and their
//! `weapon`, `weapon2`, `weapon3`, `weapon4`, `bulletConsume`, `bulletCount` and
//! `noBulletConsume` columns collapsed across every level. **[L]** Only **five of the
//! twenty-four** carry a `weapon` column at all:
//!
//! | skill | id | `weapon` | `weapon2` | `bulletConsume` | `bulletCount` |
//! |---|---:|---:|---:|---:|---:|
//! | Arrow Blow | 3001001 | 45 | 46 | 1 | 1 |
//! | Double Shot | 3001002 | 45 | 46 | 2 | 2 |
//! | Power Knockback | 3001003 | 45 | 46 | - | - |
//! | Double Stab | 4001002 | 33 | - | - | - |
//! | Lucky Seven | 4001003 | 47 | - | **-** | 2 |
//!
//! The other nineteen have **every one of those seven columns empty**, and an empty cell in
//! that file means the property is absent from the WZ node, which is not the same as `0`.
//! So **no Warrior skill and no Magician skill is gated on a weapon** - including Power
//! Strike, Slash Blast, Energy Bolt and Magic Claw. **[L]**
//!
//! Every one of those columns is the same on all of a first-job skill's levels, so one
//! [`SkillGate`] per skill is a faithful description. **That is true of these 24 and not of
//! the file** - `3111002` Arrow Rain, a second-job skill, is `bulletConsume 7` at some levels
//! and `8` at others. The test below asserts the invariance only where this module relies on
//! it, and uses Arrow Rain as the control that its parse can see variation at all; an earlier
//! version asserted it file-wide and was wrong.
//!
//! ## `bulletCount` is not an ammunition requirement, and that trap is live
//!
//! Energy Bolt (2001002) carries `bulletCount = 1` and **no weapon column and no
//! `bulletConsume`** - it is a wand spell. `research/magician-first-job.md` reads the column
//! as *"projectiles per cast"* **[L]**, from Energy Bolt's own `common` node. So a
//! `bulletCount` says how many things fly out of the caster, not how many leave the bag.
//!
//! That matters for exactly one row above: **Lucky Seven has `bulletCount 2` and no
//! `bulletConsume` at all**, where Arrow Blow and Double Shot both carry one. Read off the
//! WZ alone, Lucky Seven is *not* gated on ammunition - see [`Piece::unlocks`] and the
//! honest hedge on the throwing stars in [`THIEF`].
//!
//! # The weapon-type numbering is the client's own, and [`crate::damage::WeaponClass`] owns it
//!
//! `research/damage-formula.md` §1.3: `FUN_14025e000` opens `lea eax,[r8-0x1e] / cmp eax,0x11
//! / ja`, so the client's weapon switch covers exactly **30..=47**, it is `itemId / 10000 -
//! 100`, and `Skill.wz` puts the same code in a skill's `weapon` field. **[L]** This module
//! does not restate that mapping - it calls [`crate::damage::WeaponClass::from_code`] and
//! [`crate::damage::WeaponClass::from_item_id`], and adds only the plain-English name
//! ([`weapon_name`]) that the enum does not carry.
//!
//! Every distinct `weapon` value anywhere in `skills.txt` is `{30, 31, 32, 33, 43, 44, 45,
//! 46, 47}` and every one of them resolves through `WeaponClass::from_code`. **[L]** - there
//! is no code in the skill archive that the damage module cannot name.
//!
//! # Ammunition lives in the USE tab, and that is now [L] rather than [I]
//!
//! **This was the question most likely to sink the run**, because "arrows go in USE" is a
//! memory of a different version of this game and `C:\Users\user\Desktop\ModernMapleSource`
//! has scored 1 of 8 lifetime here. It is settled off this client instead.
//!
//! `store::InventoryType::for_item` computes `itemId / 1_000_000` and its own doc block
//! marks that **[I]** for everything except the equip family: *"the family's usual convention
//! and nothing in this client has been read to confirm them"*. The client's own
//! `GetInventoryType` is `FUN_1403e8af0`, named in `crates/net/src/shop.rs`. Disassembled with
//! `tools/listing.py` (whose documented positive control on `0x140304100` was run first and
//! reproduced its three published read addresses exactly):
//!
//! ```text
//! 1403e8af6  mov  eax, 0x431bde83     ; the signed-division magic for /1000000:
//! 1403e8afb  imul ecx                 ;   ceil(2^50 / 10^6) = 1125899907, shift 18
//! 1403e8afd  mov  ebx, edx
//! 1403e8aff  sar  ebx, 0x12
//! 1403e8b09  cmp  ebx, 1              ; is it the equip family?
//! 1403e8b0c  jne  0x1403e8b63         ; NO  ->
//! 1403e8b63  mov  eax, ebx            ;        return itemId / 1000000, unmodified
//! 1403e8b6a  ret
//! ```
//!
//! **For every item id outside `1xxxxxx`, this client's own `GetInventoryType` returns
//! `itemId / 1_000_000` and nothing else.** **[L]** Arrows are `206xxxx`/`206 1xxx` and
//! throwing stars are `207xxxx`, so both return **2**, and `2` is the USE tab - which is
//! [L] separately, from the `0x0107` decode `net::inventory::CLIENT_INVENTORY_MOVE`
//! documents as `1 Equip, 2 Consume, 3 Install, 4 Etc, 5 Cash, 6 Decoration`.
//!
//! The `1xxxxxx` arm is the only one with more to it: it calls an item-template lookup and
//! returns **6** when the template's `+0x18` is non-zero, otherwise 1. That is the cash-equip
//! fork and it does not touch ammunition.
//!
//! So [`AMMUNITION_TAB`] is `Use`, and **the existing `!item` GM command already puts it
//! there** - `Session::gm_item` routes on `store::InventoryType::for_item`, which computes
//! the identical quotient. No new command is needed to get ammunition into the right tab.
//!
//! ## What is NOT established: whether a claw refuses to swing with an empty USE tab
//!
//! Stated plainly because it is the one thing here a client run could still contradict.
//! `.text` was scanned for the two byte forms of the throwing-star range test
//! (`imm32 0x001F95F0` and `disp32 -0x1F95F0`), **enumerated rather than filtered**: 14 byte
//! hits, of which **9 decode as real instructions** in `FUN_1402cf5c0` (the bundle encoder),
//! `FUN_140304450` (the bundle decoder), `FUN_1404ba100` and `FUN_141fa77a0` and
//! `FUN_141faecc0` (shop rows), `FUN_1403e1820`, `FUN_14039af80`, `FUN_140416840`,
//! `FUN_14115bf50`. The tenth, `FUN_14288e9a0`, is a byte pattern inside data and decodes as
//! no instruction at all.
//!
//! Every one of those is item bookkeeping. **None is an attack path.** But that is a negative
//! from a scan with a named blind spot, and `CLAUDE.md` is emphatic that such a negative
//! retracts nothing: **a fire-path bullet lookup would naturally walk the USE bag calling one
//! of those nine predicates rather than inline the constant**, so this enumeration cannot
//! rule one out. Hand the owner the stars regardless; they cost one `!item` line.
//!
//! # The requirement columns are missing from `equips.txt`, so they were read from the WZ
//!
//! `research/damage-formula.md` §6.4 records that `gm-handbook/equips.txt` is missing
//! columns, and **a requirement column is among them**: its header is `itemId, tuc, incSTR,
//! incDEX, incINT, incLUK, incMHP, incMMP, incSpeed, incJump, incWAT, incMAD, incPDD, incMDD,
//! incACC, incEVA, incCRT, incCRD, tradeBlock` - no `reqLevel`, no `reqSTR/DEX/INT/LUK`, no
//! `reqJob`. §6.4 names all of those explicitly as absent. **So "this item has no
//! requirement" is a claim `equips.txt` cannot support.**
//!
//! It is not left there. All **230** weapon images in `Character.wz/Weapon/Weapon_000.wz`
//! were read directly with `wz-dump` (0 unreadable) and every one carries `reqLevel`,
//! `reqSTR`, `reqDEX`, `reqINT`, `reqLUK` and `reqJob` in its `info` node. **[L]** The fields
//! vary properly - `reqLevel` takes 20 distinct values from 0 to 70 across the 230 - so this
//! is a reading, not a default. Every [`Requirements`] value below came from that scan.
//!
//! `reqJob` is a **bitmask**, not a job id: `1` Warrior, `2` Magician, `4` Bowman, `8` Thief,
//! `16` Pirate. **[D]**, and measured rather than assumed - all 13 bows and all 10 crossbows
//! are `4`, all 31 claws are `8`, all 8 staves are `2`, with no exceptions in any class; the
//! only values in the whole archive are `{0, 1, 2, 3, 4, 8, 9, 13}`, every one of them a
//! subset of those five bits; and **`16` never appears**, which independently reproduces
//! `damage-formula.md` §1.3's "this client has no pirates".
//!
//! # The branch that cannot be completed from a bare character, and it is two of them
//!
//! **There is no zero-requirement bow, crossbow or claw in this client.** The cheapest of
//! each, measured:
//!
//! | class | cheapest item | `reqLevel` | stat | `reqJob` |
//! |---|---|---:|---|---:|
//! | Bow | `1452000` War Bow | 10 | DEX 25 | 4 |
//! | Crossbow | `1462000` Crossbow | 10 | DEX 25 | 4 |
//! | Claw | `1472000` Garnier | 10 | LUK 25 | 8 |
//! | Dagger | `1332000` Razor | **5** | **none** | **0** |
//! | 1H Sword | `1302000` Sword | **0** | **none** | **0** |
//!
//! and **every one of the 11 throwing stars carries `reqLevel 10`**, where **no arrow carries
//! a requirement at all**. So the Bowman branch and the Lucky Seven half of the Thief branch
//! cannot be equipped by a level-1 character no matter which item is chosen, and substituting
//! something plausible would be inventing data this client does not have.
//!
//! **In practice this is not a blocker, and the reason is worth writing down.** A character
//! that reached a first job through this server's own advancement already satisfies both
//! gates: `crate::jobs::LEVEL_MINIMUM` is 10 and `crate::jobs::STAT_MINIMUM` is 35 in the
//! branch's own stat, and 35 > 25. **[D]** The gap is `!job`, which sets the job id directly
//! and bypasses that check - a character put into job 300 that way may hold DEX 4 and be
//! unable to equip anything it can cast with. That is what [`Requirements::met_by`] is for.

use net::opcode::Character;
use store::InventoryType;

use crate::damage::WeaponClass;

// ---------------------------------------------------------------------------------------
// Job bitmask
// ---------------------------------------------------------------------------------------

/// `reqJob` bit for a Warrior. **[D]** - see the module docs for the measurement.
pub const JOB_BIT_WARRIOR: u32 = 1;
/// `reqJob` bit for a Magician. **[D]**
pub const JOB_BIT_MAGICIAN: u32 = 2;
/// `reqJob` bit for a Bowman. **[D]**
pub const JOB_BIT_BOWMAN: u32 = 4;
/// `reqJob` bit for a Thief. **[D]**
pub const JOB_BIT_THIEF: u32 = 8;
/// `reqJob` bit for a Pirate. **Never set on any weapon in this client** - the archive's
/// values are all subsets of the four bits above, which is the same absence
/// `research/damage-formula.md` §1.3 reads out of the weapon switch. **[D]**
pub const JOB_BIT_PIRATE: u32 = 16;

/// The `reqJob` bit a job id satisfies. `0` for a beginner, which meets only `reqJob 0`.
///
/// Keyed on `job / 100` so a second-job id (`110`, `120`, `210`, …) resolves to its branch.
pub fn job_bit(job: u16) -> u32 {
    match job / 100 {
        1 => JOB_BIT_WARRIOR,
        2 => JOB_BIT_MAGICIAN,
        3 => JOB_BIT_BOWMAN,
        4 => JOB_BIT_THIEF,
        5 => JOB_BIT_PIRATE,
        _ => 0,
    }
}

