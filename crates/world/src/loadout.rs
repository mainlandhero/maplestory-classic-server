/// What an item asks of the character before it can be worn.
///
/// **Every field is [L]**, read out of the item's own `info` node in
/// `Character.wz/Weapon/Weapon_000.wz` (weapons) or `Item.wz/Consume/0207.img` (throwing
/// stars) with `target/release/wz-dump.exe`. `gm-handbook/equips.txt` carries **none** of
/// these columns - see the module docs.
///
/// `0` means the property is zero or absent, and for a requirement those are the same thing:
/// a `reqDEX` of 0 and no `reqDEX` node both mean "asks nothing of DEX". That is deliberately
/// unlike the units trap in `crate::damage`, where `0` had to be distinguished from unset.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub struct Requirements {
    pub level: u32,
    pub strength: u32,
    pub dexterity: u32,
    pub intelligence: u32,
    pub luck: u32,
    /// `reqJob`, a **bitmask** - see [`job_bit`]. `0` means any job.
    pub job_mask: u32,
}

impl Requirements {
    /// Asks for nothing at all.
    pub const NONE: Requirements = Requirements {
        level: 0,
        strength: 0,
        dexterity: 0,
        intelligence: 0,
        luck: 0,
        job_mask: 0,
    };

    /// Whether this item asks for nothing.
    pub fn is_free(&self) -> bool {
        *self == Requirements::NONE
    }

    /// Whether a character satisfies every clause.
    ///
    /// **This is what the client checks, not what this server checks.** The server has never
    /// validated an equip and does not start here; `research/equip-stats.md` establishes that
    /// the 125-byte equipped-item body carries **no requirement field at all** and that the
    /// client loads all six out of the WZ into `ITEMINFO` itself (`reqSTR -> +0x58` …
    /// `reqLevel -> +0x78`, and `FUN_14038c560` re-reads `reqLevel` live). **[L]**
    ///
    /// Whether the client then *refuses* an equip that fails is **not established here** and
    /// is worth one look on screen. Use this to warn, never to refuse - `CLAUDE.md`'s
    /// always-answer rule, and a GM command that silently declines is worse than one that
    /// hands over an item the client greys out.
    pub fn met_by(&self, level: u32, chr_job: u16, str_: u32, dex: u32, int: u32, luk: u32) -> bool {
        level >= self.level
            && str_ >= self.strength
            && dex >= self.dexterity
            && int >= self.intelligence
            && luk >= self.luck
            && (self.job_mask == 0 || self.job_mask & job_bit(chr_job) != 0)
    }

    /// The same check against a live character record.
    pub fn met_by_character(&self, chr: &Character) -> bool {
        self.met_by(
            chr.level,
            chr.job,
            u32::from(chr.strength),
            u32::from(chr.dexterity),
            u32::from(chr.intelligence),
            u32::from(chr.luck),
        )
    }

    /// Every clause this character fails, in plain words. Empty when [`Self::met_by`] holds.
    pub fn unmet_clauses(&self, chr: &Character) -> Vec<String> {
        let mut out = Vec::new();
        if chr.level < self.level {
            out.push(format!("level {} (has {})", self.level, chr.level));
        }
        for (want, has, label) in [
            (self.strength, u32::from(chr.strength), "STR"),
            (self.dexterity, u32::from(chr.dexterity), "DEX"),
            (self.intelligence, u32::from(chr.intelligence), "INT"),
            (self.luck, u32::from(chr.luck), "LUK"),
        ] {
            if has < want {
                out.push(format!("{label} {want} (has {has})"));
            }
        }
        if self.job_mask != 0 && self.job_mask & job_bit(chr.job) == 0 {
            out.push(format!("job mask {} (job {} is bit {})", self.job_mask, chr.job, job_bit(chr.job)));
        }
        out
    }
}

