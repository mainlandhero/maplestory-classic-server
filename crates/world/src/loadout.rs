/// The Magician branch, job 200. **`pieces` is empty and that is measured.**
///
/// All six Magician skills were checked column by column in `gm-handbook/skills.txt` and
/// **not one carries `weapon`, `weapon2`, `weapon3`, `weapon4`, `bulletConsume` or
/// `noBulletConsume`**. **[L]** The single non-empty cell anywhere in that group is Energy
