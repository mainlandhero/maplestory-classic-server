// =======================================================================================
//
// **WIRED on 2026-08-28 - this section is kept as the record of what was done.** `!kit` in
// `session::gm` calls `loadout_for`, hands each piece over through the shared `give_item`, and
// reports what the character cannot equip. The paragraph below said "nothing above is
// reachable from a running server", which was true when the agent wrote it and is not now.
//
// ## 1. `gm_item`'s body wants extracting first, and there is a precedent for saying so
//
// `session/inventory.rs`'s own header records that the give-an-item path already existed
// twice - "once for `!item` and once for a shop purchase - and the two copies had already
// drifted". Do not make a third. Lift the tail of `Session::gm_item` (everything from
// `let is_equip = ...` to the `inventory_added_replies` call) into
//
//     fn give_item(&mut self, chr_id: u32, inv: store::InventoryType, item_id: u32, count: u16)
//         -> Result<Vec<store::InvRow>, String>
//
// and have `!item` and `!kit` both call it. `!kit` then adds no new wire path at all, which
// is the point: `!item 2060000 1000` already works today and `!kit` is only a shorthand for
// three of them.
//
// ## 2. The command
//
//     "kit" => self.gm_kit(arg),                        // session/gm.rs, beside "item"
//
//     /// `!kit [jobId]` - every item this branch's first-job skills need.
//     pub(super) fn gm_kit(&mut self, arg: &str) -> Vec<Reply> {
//         let Some(chr) = self.claimed_character() else {
//             return self.gm_ack("!kit REFUSED: no character is claimed.".to_string());
//         };
//         let job = arg.trim().parse::<u16>().unwrap_or(chr.job);
//         let Some(kit) = crate::loadout::loadout_for(job) else {
//             return self.gm_ack(format!(
//                 "!kit: job {job} is not a first job. Try 100, 200, 300 or 400."));
//         };
//         if kit.needs_nothing() {
//             return self.gm_ack(format!(
//                 "{} needs nothing: not one of its six skills carries a Skill.wz weapon \
//                  column. That is measured, not an omission - see world::loadout.",
//                 kit.job_name));
//         }
//         let mut out = Vec::new();
//         for p in kit.pieces {
//             let inv = store::InventoryType::for_item(p.item_id).expect("1..5");
//             match self.give_item(chr.id, inv, p.item_id, p.quantity) { .. }
//             // one gm_ack line per piece, naming p.name, p.item_id and inv
//         }
//         // ...then the warnings in §3.
//         out
//     }
//
// Add `!kit [jobId]` to the help string in `session/mod.rs` - it is one line and it is the
// only place a person finds out the command exists.
//
// ## 3. Warn, never refuse - and there are exactly three things to warn about
//
// `CLAUDE.md`'s always-answer rule. A `!kit` that declines because a stat is low is worse
// than one that hands the item over and says so.
//
//   a. **Requirements.** `kit.unequippable(&chr)` returns every piece the character cannot
//      wear with the failing clauses already formatted. This is the `!job 300` case: a
//      character dropped into a job without the stats. Print it; still give the items.
//
//   b. **The Thief needs two weapons.** `THIEF.pieces` is Razor, Garnier and stars, and
//      Double Stab (weapon 33) and Lucky Seven (weapon 47) cannot both be satisfied by one
//      equipped item. Say "swap the weapon between the two skills" in the ack, or a failed
//      Lucky Seven will read as a broken skill when it is a Razor still in the slot.
//
//   c. **The bow and the crossbow take different arrows.** If `kit.alternative` is ever
//      handed out instead, 1462000 needs 2061000 and not 2060000.
//
// ## 4. What NOT to build
//
// * **No new packet.** Ammunition reaches the USE tab through the same
//   `inventory_added_replies` path everything else uses, and `net::bag` already emits the
//   49-byte throwing-star body (`bundle_has_serial`) rather than the 41-byte one. A `!kit`
//   that built its own item body would have to get that gate right a second time.
// * **No equip-requirement enforcement.** This server has never validated an equip and this
//   is not the place to start; `Requirements::met_by` exists to word a warning.
// * **No auto-equip.** Nothing here puts an item in the weapon slot - the owner drags it, which
//   is also the only way to observe whether the client honours `reqLevel`/`reqDEX` at all.
//   That observation is worth more than the convenience.
